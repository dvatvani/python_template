"""Tests rendering the copier template and checking the generated projects work."""

import pytest
import yaml
from pytest_copier.plugin import CopierFixture, CopierProject


@pytest.fixture
def project(copier: CopierFixture, tmp_path) -> CopierProject:
    return copier.copy(tmp_path / "project")


@pytest.fixture
def git_project(project: CopierProject) -> CopierProject:
    """A generated project committed to a fresh git repository, as a user would set it up."""
    project.run("git init --initial-branch=main")
    project.run("uv lock")
    project.run("git add -A")
    project.run("git commit -m 'feat: first commit'")
    return project


@pytest.mark.parametrize(
    ("package_name", "project_slug", "module"),
    [
        ("demo", "demo", "demo"),
        ("Demo Project", "demo-project", "demo_project"),
        ("data_tools", "data-tools", "data_tools"),
        ("my-cli", "my-cli", "my_cli"),
    ],
)
def test_package_name_derivation(
    copier: CopierFixture, tmp_path, package_name: str, project_slug: str, module: str
) -> None:
    project = copier.copy(tmp_path / "project", package_name=package_name)

    assert (project / "src" / module / "__init__.py").exists()
    assert f'name = "{project_slug}"' in (project / "pyproject.toml").read_text()
    assert (
        f"from {module}.example import hello"
        in (project / "tests" / "test_hello.py").read_text()
    )


@pytest.mark.parametrize(
    "package_name", ["", "2fast", "my.project", "my project!", "-demo", "demo_"]
)
def test_invalid_package_name_rejected(
    copier: CopierFixture, tmp_path, package_name: str
) -> None:
    with pytest.raises(
        ValueError, match="Validation error for question 'package_name'"
    ):
        copier.copy(tmp_path / "project", package_name=package_name)


def test_generated_files(project: CopierProject) -> None:
    for path in [
        ".copier-answers.yml",
        ".gitignore",
        ".pre-commit-config.yaml",
        ".github/workflows/ci.yaml",
        ".github/dependabot.yml",
        "AGENTS.md",
        "README.md",
        "justfile",
        "pyproject.toml",
        "src/demo_project/example.py",
        "tests/test_hello.py",
    ]:
        assert (project / path).is_file(), path

    # No un-rendered template files should leak into the project
    assert not list(project.path.rglob("*.jinja"))
    assert not (project / ".github/workflows/copier.yaml").exists()
    assert not (project / "marimo_notebooks").exists()


def test_answers_recorded(project: CopierProject) -> None:
    assert project.answers == {
        "package_name": "Demo Project",
        "project_description": "A project generated by the template test suite",
        "github_username": "octocat",
    }


def test_github_config_is_valid(project: CopierProject) -> None:
    ci = yaml.safe_load((project / ".github/workflows/ci.yaml").read_text())
    assert set(ci["jobs"]) == {"lint", "test"}
    # GitHub expressions must survive rendering untouched
    assert (
        "${{ github.workflow }}" in (project / ".github/workflows/ci.yaml").read_text()
    )

    dependabot = yaml.safe_load((project / ".github/dependabot.yml").read_text())
    assert {u["package-ecosystem"] for u in dependabot["updates"]} == {
        "uv",
        "github-actions",
        "pre-commit",
    }
    assert {u["schedule"]["interval"] for u in dependabot["updates"]} == {"weekly"}


def test_ci_steps_pass(git_project: CopierProject) -> None:
    """Run the same commands as the generated project's CI workflow."""
    git_project.run("uv sync --locked")
    git_project.run("uv run ruff format --check")
    git_project.run("uv run ruff check")
    git_project.run("uv run ty check")
    assert "1 passed" in git_project.run("uv run pytest")


def test_just_recipes_pass(git_project: CopierProject) -> None:
    git_project.run("just install")
    git_project.run("just check")
    assert "1 passed" in git_project.run("just test")
    # `just check`/`just test` must not leave the working tree dirty
    assert git_project.run("git status --porcelain") == ""


def test_commit_msg_hook_enforces_conventional_commits(
    git_project: CopierProject,
) -> None:
    git_project.run("just install")
    with pytest.raises(RuntimeError, match="commit validation: failed"):
        git_project.run("git commit --allow-empty -m 'not a conventional commit'")
    git_project.run("git commit --allow-empty -m 'chore: a conventional commit'")


def test_project_builds(git_project: CopierProject) -> None:
    git_project.run("uv build")
    assert sorted(p.name for p in (git_project / "dist").glob("demo_project-*")) == [
        "demo_project-0.0.0-py3-none-any.whl",
        "demo_project-0.0.0.tar.gz",
    ]


def test_update_template_recipe(git_project: CopierProject) -> None:
    """Updating to the same template version should succeed and change nothing."""
    git_project.run("just update-template")
    assert git_project.run("git status --porcelain") == ""
